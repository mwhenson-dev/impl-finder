package dev.mwhenson.implFinder.plugin.integration

import org.gradle.testkit.runner.GradleRunner
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNotNull
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.File
import java.util.zip.ZipFile

/**
 * These tests exercise the real [dev.mwhenson.implFinder.plugin.ImplFinderPlugin] against a real Kotlin
 * Symbol Processing compilation, using the actual `Annotations` and `SymbolProcessor` subprojects (via an
 * included build) rather than any hand-rolled stand-in. This is slower than the unit tests in
 * [dev.mwhenson.implFinder.plugin.ImplFinderPluginTest], but it verifies the whole pipeline end to end:
 * annotated sources go in, a `Manifest.json` comes out of KSP, and that file ends up in the produced jar.
 *
 * @author mwhenson
 */
class IntegrationTests {

    @TempDir
    lateinit var testDir: File

    private val repoRoot: File = File("..").canonicalFile

    @BeforeEach
    fun setup() {
        check(File(repoRoot, "Annotations").isDirectory) {
            "Expected to find the Annotations project at $repoRoot; is the GradlePlugin test working directory not the project directory?"
        }

        File(testDir, "settings.gradle.kts").writeText(
            """
            pluginManagement {
                repositories {
                    gradlePluginPortal()
                    mavenCentral()
                    google()
                }
            }

            rootProject.name = "integration-test-project"

            includeBuild("${repoRoot.invariantSeparatorsPath}")
            """.trimIndent()
        )

        File(testDir, "build.gradle.kts").writeText(
            """
            plugins {
                kotlin("jvm") version "2.3.10"
                id("com.google.devtools.ksp") version "2.3.7"
                id("java-library")
                id("dev.mwhenson.impl-finder")
            }

            repositories {
                mavenCentral()
            }

            dependencies {
                implementation("dev.mwhenson.impl-finder:Annotations")
                ksp("dev.mwhenson.impl-finder:SymbolProcessor")
            }
            """.trimIndent()
        )

        val sourceDir = File(testDir, "src/main/kotlin/com/example")
        sourceDir.mkdirs()
        File(sourceDir, "Greeter.kt").writeText(
            """
            package com.example

            import dev.mwhenson.implFinder.Implementation

            interface Greeter {
                fun greet(): String
            }

            @Implementation
            class EnglishGreeter : Greeter {
                override fun greet() = "hello"
            }
            """.trimIndent()
        )
    }

    @Test
    fun `manifest generated by KSP for a real compilation is packaged into the produced jar`() {
        val result = GradleRunner.create()
            .withProjectDir(testDir)
            .withPluginClasspath()
            .withArguments("jar")
            .build()

        assertTrue(result.output.contains("BUILD SUCCESSFUL"))

        val jarFile = File(testDir, "build/libs").listFiles { file -> file.extension == "jar" }?.first()
        assertNotNull(jarFile, "Expected a jar to be produced in build/libs")

        ZipFile(jarFile!!).use { zip ->
            val entry = zip.getEntry("dev/mwhenson/implFinder/manifest/Manifest.json")
            assertNotNull(entry, "Expected Manifest.json to be present in the produced jar")

            val actualContent = zip.getInputStream(entry).bufferedReader().use { it.readText() }
            assertEquals(
                """{"version":1,"entries":{"com.example.Greeter":["com.example.EnglishGreeter"]}}""",
                actualContent
            )
        }
    }
}