package dev.mwhenson.implFinder.runtime

/**
 * Holds a no-argument factory for each implementation that was found for the shared contract [T],
 * without invoking any of them. Individual implementations are only constructed once they're reached
 * through [iterator], e.g. by a `for` loop or a `kotlin.collections` extension like `map` - not by
 * every implementation at once. Each one is then cached, so revisiting the same element on this same
 * instance - whether by iterating again or some other means - always returns the exact same object.
 *
 * Every implementation held by a given instance must implement the same contract [T] - that's fixed
 * by the type argument supplied when the instance is constructed.
 *
 * Instances of this class are created by code generated by the impl-finder Gradle plugin - it isn't
 * meant to be constructed directly.
 *
 * @param T the contract/interface every implementation held by this instance implements
 *
 * @author mwhenson
 */
class LazyImplementations<out T : Any>(factories: List<() -> T>) : Iterable<T> {

    private val lazyInstances: List<Lazy<T>> = factories.map { factory -> lazy { factory() } }

    override fun iterator(): Iterator<T> = object : Iterator<T> {
        private val delegate = lazyInstances.iterator()

        override fun hasNext(): Boolean = delegate.hasNext()

        override fun next(): T = delegate.next().value
    }
}
